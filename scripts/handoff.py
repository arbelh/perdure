def load_lint():
    """Import lint() from the sibling rot-lint.py (hyphenated filename)."""
    path = Path(__file__).resolve().parent / "rot-lint.py"
    spec = importlib.util.spec_from_file_location("rot_lint", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.lint


def git(args, cwd):
    try:
        r = subprocess.run(["git", *args], cwd=cwd, capture_output=True,
                           text=True, timeout=20)
        return r.stdout.strip() if r.returncode == 0 else ""
    except Exception:
        return ""


def frontmatter(lines):
    """Return the frontmatter dict, or None when the file has none."""
    if not lines or lines[0].strip() != "---":
        return None
    fm = {}
    for line in lines[1:60]:
        if line.strip() == "---":
            return fm
        m = re.match(r"([\w-]+):\s*(.+)", line)
        if m:
            fm[m.group(1)] = m.group(2).strip()
    return None


def section(lines, heading):
    """Lines of the `# <heading>` section, up to the next H1."""
    out, active = [], False
    for line in lines:
        if re.match(rf"#\s+{re.escape(heading)}\s*$", line):
            active = True
            continue
        if active and re.match(r"#\s+\S", line):
            break
        if active:
            out.append(line)
    return [l.rstrip() for l in out]


def first_text(lines):
    for l in lines:
        if l.strip() and not l.strip().startswith(("(", "<!--")):
            return l.strip()
    return ""


def first_para(lines):
    """Join the first paragraph — a one-line extraction can silently drop a
    continuation line that carries the safety condition ("ONLY IF ...")."""
    para, started = [], False
    for l in lines:
        t = l.strip()
        if not t:
            if started:
                break
            continue
        if not started and t.startswith(("(", "<!--")):
            continue
        started = True
        para.append(t)
    return " ".join(para)


def excerpt(text, cap=160):
    """Word-boundary cap with ellipsis; strip markdown bold markers."""
    text = text.replace("**", "").strip()
    if len(text) <= cap:
        return text
    cut = text[:cap].rsplit(" ", 1)[0].rstrip(",;:")
    return cut + " …"


def date_of(value):
    m = re.search(r"(20\d\d-\d\d-\d\d)", value or "")
    return m.group(1) if m else ""


class Record:
    def __init__(self, path: Path, root: Path):
        self.path = path
        self.rel = path.relative_to(root)
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        fm = frontmatter(lines)
        self.freeform = fm is None or "status" not in fm
        self.status = (fm or {}).get("status", "").strip().lower()
        self.updated = date_of((fm or {}).get("updated", ""))
        self.updated_raw = (fm or {}).get("updated", "").strip().strip("\"'").strip()
        self.goal = first_para(section(lines, "Goal"))
        if not self.goal:  # freeform records: the H1 title is the descriptor
            for l in lines:
                m = re.match(r"#\s+(\S.*)", l)
                if m:
                    self.goal = re.sub(r"^Workflow:\s*", "", m.group(1).strip())
                    break
        self.goal = excerpt(self.goal, 220)
        # The record's own status bullet (freeform records). Shown ONLY when
        # the record is lint-clean, clearly attributed, capped, time-scoped —
        # the lint screens bullet statuses against the body the same way it
        # screens frontmatter ones, which is what makes quoting it safe.
        self.status_bullet = ""
        for l in lines:
            m = re.match(r"-\s+\*\*Status[:*\s]*\**:?\s*(.+)", l)
            if m:
                self.status_bullet = excerpt(m.group(1))
                break
        self.next_step = excerpt(first_para(section(lines, "Next step")), 300)
        self.named_files = {m for m in re.findall(
            r"`([\w./-]+/[\w.-]+\.\w{2,7})`", "\n".join(lines))
            if not m.startswith("perdure/")}
        self.findings = []
        self.stale_activity = ""

    @property
    def is_open(self):
        return sv.is_open(self.status)

    @property
    def is_terminal(self):
        return sv.is_gate_terminal(self.status)

    @property
    def is_parked(self):
        return sv.is_parked(self.status)

    def cite(self):
        asof = f" — as of {self.updated}" if self.updated else ""
        return f"[`{self.rel}`]({self.href}){asof}"


def has_supersessor(text: str) -> bool:
    """True iff a `superseded-by:` frontmatter key names an actual supersessor.

    An EMPTY YAML list (`superseded-by: []`) means nothing supersedes this —
    it is the value the /perdure:decide template ships, so treating it as a
    death marker filed every product-created ADR under "Rejected/superseded"
    (pre-publish verification, 2026-08-31). Same for an empty string, `~`,
    `null`, or a bare key.
    """
    m = re.search(r"^superseded-by:[ \t]*(.*)$", text, re.M)
    if not m:
        return False
    v = re.sub(r"\s*#.*$", "", m.group(1)).strip().strip("\"'").strip()
    if v == "":
        # bare key: a BLOCK-form list may follow as indented "- item" lines.
        # Missing this rendered a genuinely superseded ADR under "Decisions in
        # force" — the dangerous direction (review 2026-08-31).
        for line in text[m.end():].splitlines():
            if not line.strip():
                continue
            return bool(re.match(r"^[ \t]+-[ \t]*\S", line))
        return False
    if re.fullmatch(r"\[\s*\]", v) or v.lower() in ("~", "null", "none", "-"):
        return False
    return True


def adr_id_title(text: str, stem: str):
    """(id, title) of one ADR, read where _decision_ids reads an id: the first
    H1 after the frontmatter, outside code fences, in the `# ADR-NNN: Title`
    form; else the frontmatter's `id:` and `title:`. A `# ADR-003` inside a
    fenced example, or a later heading, is never read (it was, 4.3.0). The id
    is "?" when neither place holds one; the title falls back to the stem."""
    if text.startswith("\ufeff"):
        text = text[1:]
    lines = text.splitlines()
    fm_lines, body = [], 0
    if lines and lines[0].strip() == "---":
        for i, line in enumerate(lines[1:80], start=1):
            if line.strip() == "---":
                fm_lines, body = lines[1:i], i + 1
                break
    h1 = di.first_h1(lines[body:])
    m = re.match(r" {0,3}#[ \t]+ADR-(\d+):[ \t]*(.+)$", h1, re.I) if h1 else None
    if m:
        return m.group(1), m.group(2).strip()
    # YAML frontmatter form (what the /perdure:decide template writes)
    aid = next((im.group(1) for im in (di._FM_ID.match(l.rstrip()) for l in fm_lines)
                if im), "?")
    tm = next((t for t in (re.match(r"title:\s*(.+?)\s*$", l) for l in fm_lines) if t), None)
    return aid, (tm.group(1).strip().strip("\"'") if tm else stem)


def collect_adrs(root: Path):
    """Parse ADRs (bullet-metadata or YAML form) into (id, title, status, date)."""
    adrs = []
    ddir = root / "perdure" / "decisions"
    if not ddir.is_dir():
        return adrs
    for p in sorted(ddir.glob("*.md")):
        if p.name == "INDEX.md":
            continue
        text = p.read_text(encoding="utf-8", errors="replace")
        aid, title = adr_id_title(text, p.stem)
        sm = re.search(r"^-\s*\*\*Status\**[:*\s]*\**:?\s*(.+)$", text, re.M) or \
             re.search(r"^status:\s*(.+)$", text, re.M)
        dm = re.search(r"^-\s*\*\*Date\**[:*\s]*\**:?\s*([\d-]+)", text, re.M) or \
             re.search(r"^date:\s*([\d-]+)", text, re.M)
        raw = sm.group(1).strip().rstrip("*").strip() if sm else ""
        low = raw.lower()
        # Classify on the WHOLE status text plus superseded-by markers anywhere
        # in the file: "Accepted (superseded by ADR-9)" is NOT in force, and a
        # first-word parse rendered exactly that under "in force" (review
        # 2026-08-26). ADRs are not rot-linted; parse conservatively instead.
        if any(k in low for k in ("superseded", "rejected", "deprecated")) or \
           has_supersessor(text):
            cls = "dead"
        elif low.startswith("accepted"):
            cls = "accepted"
        elif low.startswith("proposed"):
            cls = "proposed"
        else:
            cls = "unknown"
        adrs.append((aid, title, cls, raw, dm.group(1) if dm else "",
                     p.relative_to(root)))
    return adrs


def build(root: Path):
    lint = load_lint()
    wdir = root / "perdure" / "workflows"
    records = []
    for p in sorted(wdir.rglob("*.md")):
        if p.name == "INDEX.md":
            continue
        rec = Record(p, root)
        try:
            rec.findings = lint(p)
        except Exception as e:
            rec.findings = [("lint-error", 0, str(e)[:120], 0, "")]
        records.append(rec)

    # git is used when a git top sits at or ABOVE the project root, and runs
    # from the project root, so record-relative paths mean what they mean to
    # rot-lint.py. Before 4.3.0 this was gated on .git sitting AT the root, so
    # a project inside a repo subfolder skipped staleness while still stamping
    # a commit (scripts/_paths.py holds the shared definition).
    in_git = pa.git_top(root) is not None

    # last repo touch per record (freeform records have no `updated:` key)
    for rec in records:
        rec.touched = rec.updated
        if not rec.touched and in_git:
            rec.touched = git(["log", "-1", "--format=%ad", "--date=short",
                               "--", str(rec.rel)], root)
        if not rec.touched:
            try:
                rec.touched = datetime.date.fromtimestamp(
                    rec.path.stat().st_mtime).isoformat()
            except OSError:
                rec.touched = ""

    # staleness: commits touching the record's named files after `updated:`
    if in_git:
        for rec in records:
            if rec.findings or not rec.updated or not rec.named_files:
                continue
            existing = [f for f in sorted(rec.named_files)[:20]
                        if (root / f).exists()]
            if not existing:
                continue
            ev = git(["log", "--oneline", f"--since={rec.updated} 23:59",
                      "--", *existing], root)
            if ev:
                n = len(ev.splitlines())
                rec.stale_activity = (f"{n} commit(s) touched files this record "
                                      f"names after its last update — statuses "
                                      f"may lag the repo")
    return records


def contradictions(r):
    return [f for f in r.findings if f[0] != "placeholder"]


def unwritten(r):
    return any(f[0] == "placeholder" for f in r.findings)


def _moment_key(value: str):
    """(instant, value) for ordering `updated:` values, or None when the value
    is no real date. An offset-less value is read as UTC for ORDERING only, and
    the raw string breaks ties, so the choice is total."""
    s = value.replace(" ", "T", 1)
    if s.endswith("Z"):
        s = s[:-1] + "+00:00"
    s = re.sub(r"([+-]\d{2})(\d{2})\Z", r"\1:\2", s)
    try:
        dt = datetime.datetime.fromisoformat(s)
    except ValueError:                   # e.g. a 2-digit fraction under 3.9
        try:
            dt = datetime.datetime.fromisoformat(s[:10])
        except ValueError:               # 2026-13-45: shaped like a date, is not one
            return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=datetime.timezone.utc)
    try:
        return (dt.timestamp(), value)
    except (OverflowError, OSError, ValueError):
        return None


def newest_update(records) -> str:
    """The newest `updated:` value among the records, as written; "" for none.

    This is the moment the page names. It depends on the records alone, never
    on HEAD or the clock, so the stamp line is the same wherever the same
    records are, and a rebase replaying closes does not rewrite line 4 once
    per commit (4.3.0). Values outside MOMENT_RE, or not a real date, are
    never quoted."""
    keyed = [k for k in (_moment_key(r.updated_raw) for r in records
                         if MOMENT_RE.match(r.updated_raw)) if k is not None]
    return max(keyed)[1] if keyed else ""


def has_conflict_markers(text: str) -> bool:
    """An unresolved merge left in the page: a `<<<<<<< ` opener followed by a
    `=======` separator or a `>>>>>>> ` closer, each at column 0. The generator
    never writes a line that starts with either."""
    lines = text.splitlines()
    for i, l in enumerate(lines):
        if re.match(r"<{7}(?: |$)", l):
            return any(re.match(r"(?:={7}$|>{7}(?: |$))", m) for m in lines[i + 1:])
    return False


def upgrade_old_page(committed: str, fresh: str) -> str:
    """Read a page in the 4.2.0 header shape as the current shape, for --check.

    4.2.0 wrote `# HANDOFF`, a blank line and OLD_STAMP_RE's line; 4.3.0 writes
    the title, MARKER, a blank line and the records-only stamp. When the
    committed page's line 3 is EXACTLY the old stamp (sha and time in their
    alphabets), its header is replaced by the fresh page's marker and stamp and
    the title and body are compared as they are — so an old page that is
    otherwise current still passes, and anything else about it does not.
    Such a page also ends in OLD_FOOTER; that one line, when it is the last
    non-empty line and EXACTLY the old footer, is read as FOOTER (4.3.0)."""
    lines = committed.split("\n")
    if (len(lines) < 3 or not lines[0].startswith("# HANDOFF") or lines[1] != ""
            or not OLD_STAMP_RE.fullmatch(lines[2])):
        return committed
    body = lines[3:]
    last = max((i for i, l in enumerate(body) if l.strip()), default=None)
    if last is not None and body[last] == OLD_FOOTER:
        body = body[:last] + [FOOTER] + body[last + 1:]
    return "\n".join([lines[0]] + fresh.split("\n")[1:4] + body)


def project_title(root: Path) -> str:
    """The name on line 1: the project's folder name as it sits in the MAIN
    checkout. Inside git, when the project root is the git top, that is the
    folder holding the shared .git (the parent of `git rev-parse
    --git-common-dir`), so a page regenerated in a worktree such as
    .claude/worktrees/<name> carries the main project's name, not the
    worktree's (4.3.0). A project in a repo subfolder keeps its folder name,
    which is the same in every worktree; outside git, and where the shared
    git folder is not a `.git` (a submodule, a bare or separate git dir), the
    folder name."""
    real = Path(os.path.realpath(str(root)))
    top = pa.git_top(real)
    if top is not None and os.path.realpath(str(top)) == str(real):
        common = git(["rev-parse", "--git-common-dir"], str(real))
        if common:
            shared = (real / common).resolve()
            if shared.name == ".git" and shared.parent.name:
                return shared.parent.name
    return real.name


def write_atomically(out: Path, text: str) -> None:
    """Write `text` to `out` through a fresh temp file beside it, then rename.

    The temp file is created by tempfile.mkstemp (O_CREAT|O_EXCL, and
    O_NOFOLLOW where the OS has it) under an unpredictable name. The name used
    before, HANDOFF.md.<pid>.tmp, was opened with Path.write_text, which
    follows a symlink planted at that predictable name and writes the page
    through it (4.3.0). The page keeps the mode of the file it replaces (a
    regular file), else the umask default; the temp file is removed on any
    failure."""
    fd, tmp = tempfile.mkstemp(dir=str(out.parent), prefix=".HANDOFF.", suffix=".tmp")
    try:
        try:
            st = os.lstat(out)
            mode = stat.S_IMODE(st.st_mode) if stat.S_ISREG(st.st_mode) else None
        except OSError:
            mode = None
        if mode is None:
            umask = os.umask(0)
            os.umask(umask)
            mode = 0o666 & ~umask
        if hasattr(os, "fchmod"):         # absent on Windows before 3.13
            os.fchmod(fd, mode)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            fd = -1
            f.write(text)
        os.replace(tmp, out)
    except BaseException:
        if fd != -1:
            try:
                os.close(fd)
            except OSError:
                pass
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def render(root: Path, records, adrs, page_dir: Path):
    for r in records:
        r.href = os.path.relpath(root / r.rel, page_dir)
    moment = newest_update(records)
    name = project_title(root)
    # a `placeholder` finding is completeness, not contradiction: the record
    # stays on the page, marked, and only contradictions withhold it
    flagged = [r for r in records if contradictions(r)]
    clean = [r for r in records if not contradictions(r)]
    open_recs = sorted([r for r in clean if r.is_open and not r.freeform],
                       key=lambda r: r.updated, reverse=True)
    other = [r for r in clean if not r.freeform and not r.is_open
             and not r.is_terminal and not r.is_parked]
    parked = sorted([r for r in clean if r.is_parked and not r.freeform],
                    key=lambda r: r.updated, reverse=True)
    done_all = sorted([r for r in clean if r.is_terminal and not r.freeform],
                      key=lambda r: r.updated, reverse=True)
    done = done_all[:8]
    freeform = [r for r in clean if r.freeform]

    L = []
    L.append(f"# HANDOFF — {name}")
    L.append(MARKER)
    L.append("")
    L.append(f"{STAMP_HEAD}`{moment or 'none'}`. **Every status below is a claim "
             f"about that moment, not now**: if any record has changed since, "
             f"regenerate before trusting this page. {STAMP_REST}")
    L.append("")

    L.append("## In flight")
    L.append("")
    if open_recs:
        for r in open_recs:
            L.append(f"- **{r.goal or '(no goal line)'}**  ")
            nxt = f"next: {r.next_step}" if r.next_step else "next step not recorded"
            L.append(f"  {nxt} · {r.cite()}")
            if r.stale_activity:
                L.append(f"  ⚠ {r.stale_activity}")
            if unwritten(r):
                L.append("  ⚠ plan or next step not written (lint: placeholder)")
    else:
        L.append("- nothing in flight in lint-clean records")
    if parked:
        L.append("")
        L.append("**Parked:**")
        for r in parked:
            L.append(f"- {r.goal or '(no goal line)'} · {r.cite()}")
            if r.stale_activity:
                L.append(f"  ⚠ {r.stale_activity}")
            if unwritten(r):
                L.append("  ⚠ plan or next step not written (lint: placeholder)")
    L.append("")

    if flagged:
        L.append("## Needs reconciliation — state claims withheld")
        L.append("")
        L.append("These records contradict themselves or git; fix them per the "
                 "convention's *Correcting a record* rules, then regenerate. "
                 "Nothing from them is summarized here — a contradicted record "
                 "misleads with the summary's authority.")
        L.append("")
        for r in flagged:
            fs = contradictions(r)
            kinds = ", ".join(sorted({f[0] for f in fs}))
            L.append(f"- [`{r.rel}`]({r.href}) — {len(fs)} finding(s): {kinds}")
        L.append("")

    if freeform:
        L.append("## Unstructured records (lint-clean) — statuses quoted, not derived")
        L.append("")
        L.append("These records predate the frontmatter convention. Each line "
                 "quotes the record's own status bullet verbatim (capped), "
                 "as of the record's last repo touch — read the record before "
                 "acting on it.")
        L.append("")
        for r in sorted(freeform, key=lambda x: x.touched, reverse=True):
            L.append(f"- **{r.goal or r.rel.name}** · [`{r.rel}`]({r.href})")
            if r.status_bullet:
                asof = f" (as of {r.touched})" if r.touched else ""
                L.append(f"  its own status line{asof}: “{r.status_bullet}”")
            else:
                L.append("  no status line found — this page asserts nothing "
                         "about its state")
            if r.stale_activity:
                L.append(f"  ⚠ {r.stale_activity}")
        L.append("")

    if other:
        L.append("## Records with unrecognized statuses — quoted, not classified")
        L.append("")
        for r in sorted(other, key=lambda x: x.touched, reverse=True):
            L.append(f"- **{r.goal or r.rel.name}** · [`{r.rel}`]({r.href})")
            L.append(f"  frontmatter status (outside the convention's vocabulary, "
                     f"as of {r.touched or 'unknown'}): “{excerpt(r.status, 120)}”")
            if r.stale_activity:
                L.append(f"  ⚠ {r.stale_activity}")
        L.append("")

    L.append("## Recently completed")
    L.append("")
    if done:
        for r in done:
            # the FULL status token: split()[0] once stripped a diligent
            # "completed (ROLLED BACK ...)" down to "completed" (review
            # 2026-08-26) — the page must never manufacture a claim the
            # record qualifies
            L.append(f"- {r.goal or '(no goal line)'} · "
                     f"{excerpt(r.status, 120) if r.status else 'terminal'} · {r.cite()}")
            if r.stale_activity:
                L.append(f"  ⚠ {r.stale_activity}")
        if len(done_all) > len(done):
            L.append(f"- … plus {len(done_all) - len(done)} older completed "
                     f"record(s) — see `perdure/workflows/`")
    else:
        L.append("- none recorded")
    L.append("")

    def adr_href(rel):
        return os.path.relpath(root / rel, page_dir)

    active_adrs = [a for a in adrs if a[2] in ("accepted", "proposed")]
    dead_adrs = [a for a in adrs if a[2] == "dead"]
    unknown_adrs = [a for a in adrs if a[2] == "unknown"]
    L.append("## Decisions in force (ADRs)")
    L.append("")
    if not active_adrs and not unknown_adrs:
        L.append("- none")
    if active_adrs:
        shown = active_adrs[-12:]
        for aid, title, _, raw, date, rel in shown:
            L.append(f"- ADR-{aid}: {title} · {excerpt(raw, 80) or 'accepted'}"
                     f" {date} · [`{rel}`]({adr_href(rel)})")
        if len(active_adrs) > len(shown):
            L.append(f"- … plus {len(active_adrs) - len(shown)} older accepted "
                     f"ADR(s) still in force — see `perdure/decisions/`")
    if unknown_adrs:
        for aid, title, _, raw, date, rel in unknown_adrs:
            L.append(f"- ADR-{aid}: {title} · **status unparseable** — read "
                     f"[`{rel}`]({adr_href(rel)}); this page asserts nothing about it")
    L.append("")
    L.append("## Rejected / superseded paths — do not re-litigate blind")
    L.append("")
    if dead_adrs:
        for aid, title, _, raw, date, rel in dead_adrs:
            L.append(f"- ADR-{aid}: {title} · {excerpt(raw, 80)} {date} · "
                     f"[`{rel}`]({adr_href(rel)})")
    else:
        L.append("- no rejected or superseded ADRs; rejected *approaches* live in "
                  "each workflow record's `# Decisions` section — read the record "
                  "before re-proposing something")
    L.append("")
    L.append("---")
    L.append(FOOTER)
    L.append("")
    return "\n".join(L)


def main():
    # Non-ASCII in the --check verdict: stdout defaults to the LOCALE encoding
    # with errors='strict', and in regenerate_handoff() a crash here is
    # indistinguishable from "stale" (review 2026-08-31).
    for _s in (sys.stdout, sys.stderr):
        try:
            _s.reconfigure(encoding="utf-8", errors="backslashreplace")
        except (AttributeError, ValueError):
            pass
    ap = argparse.ArgumentParser()
    ap.add_argument("root", nargs="?", default=".")
    ap.add_argument("--output")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the committed page differs from what the "
                         "generator would produce now (stale OR hand-tampered)")
    args = ap.parse_args()
    root = Path(args.root).resolve()
    out = Path(args.output) if args.output else root / "perdure" / "HANDOFF.md"

    if args.check:
        # INTEGRITY check by regeneration, not by trusting the page's own git
        # stamp: regenerate the page from the current records into a buffer and
        # compare against the committed file, ignoring only the volatile stamp
        # line (sha + timestamp, which always differ). This catches BOTH a
        # stale page (records changed) AND a hand-written/tampered page that
        # copied a real sha (red-team 2026-08-30: such a page passed the old
        # stamp-only check) — and it needs no git at all, so it also stops the
        # shallow-clone false-stale (the stamp commit may be outside fetched
        # history). Records are the source of truth; the page must match them.
        if not out.exists():
            print(f"stale: {out} does not exist")
            sys.exit(1)
        wdir = root / "perdure" / "workflows"
        if not wdir.is_dir():
            print(f"no records root at {wdir}", file=sys.stderr)
            sys.exit(1)
        committed = out.read_text(encoding="utf-8", errors="replace")
        # A merge of two branches that each regenerated the page leaves
        # conflict markers in it. The page is derived: the fix is never a hand
        # merge, it is a regeneration from the merged records (4.3.0).
        if has_conflict_markers(committed):
            # the command as it runs HERE: $CLAUDE_PLUGIN_ROOT is unset in a
            # terminal and in CI, where --check runs most (4.3.0)
            cmd = (f"python3 {shlex.quote(str(Path(__file__).resolve()))} "
                   f"{shlex.quote(str(root))}")
            print("stale: the committed page holds merge-conflict markers — a "
                  "derived page is never merged by hand. Regenerate it from the "
                  f"merged records: {cmd} (or /perdure:handoff in Claude Code), "
                  "then commit the result.")
            sys.exit(1)
        fresh = render(root, build(root), collect_adrs(root), out.parent.resolve())
        # a page written by 4.2.0 (sha-and-minute stamp, no marker line, the
        # old footer) is compared in the current shape; nothing else is forgiven
        committed = upgrade_old_page(committed, fresh)

        def normalize(text):
            # The stamp is no longer volatile: since 4.3.0 it names the newest
            # `updated:` among the records, not the commit or the clock, so
            # the stamp line is compared like every other line (a smuggled
            # token in it fails).
            # ⚠ staleness annotations are advisory, recomputed per generation,
            # and their commit counts move with code-only commits touching
            # record-named files — content drift they flag is not RECORD
            # drift. Forgive ONLY the generator's exact template (the count is
            # the sole variable): a free-text rewrite of an existing ⚠ line is
            # a hand edit and must fail the compare (review 2026-08-30).
            return re.sub(r"^(\s*)⚠ \d+ commit\(s\) touched files this "
                          r"record names after its last update — statuses "
                          r"may lag the repo$",
                          r"\1⚠ <staleness annotation>", text, flags=re.M)

        if normalize(committed).strip() == normalize(fresh).strip():
            print("fresh: committed page matches the current records")
            sys.exit(0)
        print("stale: the committed page does NOT match what the generator "
              "produces from the current records — records changed since it was "
              "written, or the page was hand-edited. Regenerate.")
        sys.exit(1)

    wdir = root / "perdure" / "workflows"
    if not wdir.is_dir():
        print(f"no records root at {wdir}", file=sys.stderr)
        sys.exit(1)
    records = build(root)
    page = render(root, records, collect_adrs(root), out.parent.resolve())
    out.parent.mkdir(parents=True, exist_ok=True)
    # atomic replace: parallel closes can regenerate concurrently (the hook
    # path), and a truncate-then-write window would let a concurrent --check
    # read a torn page (review 2026-08-31)
    write_atomically(out, page)
    flagged = sum(1 for r in records if contradictions(r))
    print(f"{out} written: {len(records)} record(s), {flagged} withheld for "
          f"reconciliation")
    sys.exit(0)


if __name__ == "__main__":
    main()
