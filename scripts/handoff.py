#!/usr/bin/env python3
"""handoff.py — derive a rot-aware HANDOFF orientation page from perdure/.

The naive version of this idea — mechanically extracting record content into
a one-page summary — strips the surrounding context that lets a reader catch a
stale claim, then presents the stale claim with the summary's implicit
authority. This generator exists to make that shape safe. Its rules, each
closing one of those failures:

  1. LINT-GATED INCLUSION  every record passes scripts/rot-lint.py first; a
     record with contradiction findings contributes NO state claims — it is
     listed under "Needs reconciliation" with its finding kinds. A
     `placeholder` finding marks the record on the page instead.
  2. STRUCTURED EXTRACTION ONLY  the page carries the status token, the goal
     line, and the record's own # Next step — never freeform status prose.
     Records without conforming frontmatter contribute no status at all.
  3. PROVENANCE + TIME-SCOPE  every claim names its source record and its
     as-of date; the page is stamped with the moment of the records it was
     built from (the newest `updated:` among them), and readers are told to
     regenerate when a record has changed since. The stamp no longer depends
     on HEAD or the clock (4.3.0), so the same records in the same project give
     the same page — the title is the main checkout's folder name, so a
     worktree's page matches it too (4.3.0) — with two exceptions: the
     advisory ⚠ staleness lines, whose commit counts follow the history and
     which --check forgives, and the as-of date of a record with no
     `updated:` value, taken from its last commit or, outside git, its file
     time. A page that two branches each regenerated and then merged with
     conflict markers is regenerated, never merged by hand — line 2 says so
     inside the page.
  4. STALENESS DERIVATION  commits touching a record's named files AFTER its
     `updated:` date get the record flagged "repo activity after last update".
  5. EXTERNAL-STATE HONESTY  a standing footer says external systems
     (experiments, deployments, tickets) are never checked here.

The page is DERIVED, never merged, never hand-maintained (records convention,
Extensions). Regenerate at close or before handing off; --check regenerates
the page in memory and content-compares it to the committed one (staleness
annotations normalized), so it exits 1 when the records changed, the page was
hand-edited, or the page holds merge-conflict markers — with or without git. A
page written in the 4.2.0 format (commit and minute stamp, the footer that
named $CLAUDE_PLUGIN_ROOT) still passes when its content is otherwise current.

Usage: handoff.py [project-root] [--output PATH] [--check]
       Default output: <root>/perdure/HANDOFF.md
"""
